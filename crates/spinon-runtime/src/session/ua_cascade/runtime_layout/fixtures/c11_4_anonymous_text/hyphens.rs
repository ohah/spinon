pub(super) fn find_scene(scene_id: &str) -> Option<&'static Scene> {
    SCENES.iter().find(|scene| scene.id == scene_id)
}

pub(super) fn validate_computed_hyphens(
    style: &ComputedElementStyle,
    scene: &Scene,
) -> Result<HyphensMode, RuntimeLayoutFailure> {
    let computed = style
        .properties
        .get("hyphens")
        .map(|value| value.trim())
        .unwrap_or("manual");
    if computed != scene.expected_computed {
        return Err(layout_failure(
            "unsupported_c114_hyphens_value",
            Some(style.node_id.get()),
            Some(format!(
                "computed hyphens: expected {}, got {computed:?}",
                scene.expected_computed
            )),
        ));
    }
    match computed {
        "none" if scene.mode == Some(HyphensMode::None) => Ok(HyphensMode::None),
        "manual" if scene.mode == Some(HyphensMode::Manual) => Ok(HyphensMode::Manual),
        "auto" | "balanced" => Err(layout_failure(
            "unsupported_c114_hyphens_value",
            Some(style.node_id.get()),
            Some(format!(
                "computed hyphens {computed:?} is outside the fixed profile"
            )),
        )),
        _ => Err(layout_failure(
            "unsupported_c114_hyphens_value",
            Some(style.node_id.get()),
            Some(format!("unexpected computed hyphens value {computed:?}")),
        )),
    }
}
