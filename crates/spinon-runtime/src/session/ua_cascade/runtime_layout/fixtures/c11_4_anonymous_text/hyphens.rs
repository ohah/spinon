#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum TrackKind {
    MinContent,
    MaxContent,
    Fixed30Px,
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) struct Scene {
    pub(super) id: &'static str,
    pub(super) text: &'static str,
    pub(super) expected_computed: &'static str,
    pub(super) mode: Option<HyphensMode>,
    pub(super) track: TrackKind,
    pub(super) root_width: f32,
    pub(super) min_content: f32,
    pub(super) max_content: f32,
    pub(super) min_content_height: f32,
    pub(super) max_content_height: f32,
    pub(super) expected_line_advances: &'static [f32],
}

macro_rules! scene {
    (
        $id:expr,
        $text:expr,
        $expected_computed:expr,
        $mode:expr,
        $track:expr,
        $root_width:expr,
        $min_content:expr,
        $max_content:expr,
        $min_content_height:expr,
        $max_content_height:expr,
        $expected_line_advances:expr $(,)?
    ) => {
        Scene {
            id: $id,
            text: $text,
            expected_computed: $expected_computed,
            mode: $mode,
            track: $track,
            root_width: $root_width,
            min_content: $min_content,
            max_content: $max_content,
            min_content_height: $min_content_height,
            max_content_height: $max_content_height,
            expected_line_advances: $expected_line_advances,
        }
    };
}

